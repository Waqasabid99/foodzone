import Link from "next/link";
import { nullIfMissing } from "@/lib/api/errors";
import { notFound, redirect } from "next/navigation";
import PageHeader from "@/components/dashboard/PageHeader";
import Chip from "@/components/dashboard/inventory/Chip";
import PayrollActions from "@/components/dashboard/people/PayrollActions";
import { Section } from "@/components/dashboard/products/ProductDetailsForm";
import { getAuthContext } from "@/lib/api/auth";
import { can, grantedPermissionKeys } from "@/lib/api/permissions";
import { serialize } from "@/lib/api/serialize";
import { getPayrollPeriod, listPayslips } from "@/server/services/payroll.service";
import { userNames } from "@/server/content/people-admin";
import { assertRecordAccess } from "@/server/hr/access";
import { PAYROLL_STAGE_HINT, PAYROLL_STATES, dayKey, dayLabel, durationLabel, employeeName } from "@/lib/hr";
import { formatMoney } from "@/lib/format";
import { hasPermission } from "@/lib/dashboard-nav";
import { loginHref } from "@/lib/redirects";

export const metadata = { title: "Pay run — FoodZone", robots: { index: false, follow: false } };
export const dynamic = "force-dynamic";

export default async function PayrollPeriodPage({ params }) {
  const { id } = await params;
  const principal = await getAuthContext();
  if (!principal) redirect(loginHref(`/dashboard/payroll/${id}`));
  if (!hasPermission(grantedPermissionKeys(principal), "payroll.read")) redirect("/dashboard");

  const allowed = await assertRecordAccess(principal, "payrollPeriod", id, "payroll.read")
    .then(() => true)
    .catch(() => false);
  if (!allowed) notFound();

  const raw = await nullIfMissing(getPayrollPeriod(id));
  if (!raw) notFound();
  const period = serialize(raw);

  const branchContext = period.branchId ? { branchId: period.branchId } : undefined;
  const canSeePayslips = hasPermission(grantedPermissionKeys(principal), "payslips.view_all");
  const payslips = canSeePayslips ? serialize((await listPayslips({ periodId: id, limit: 200 })).items) : [];
  const names = await userNames([period.processedById, period.approvedById]);

  const state = PAYROLL_STATES[period.status] ?? PAYROLL_STATES.DRAFT;
  const currency = payslips[0]?.employee?.currency ?? "PKR";

  return (
    <div className="flex max-w-5xl flex-col gap-6">
      <PageHeader
        title={period.name}
        description={`${dayLabel(dayKey(period.startDate), { weekday: false })} to ${dayLabel(dayKey(period.endDate), { weekday: false })}${period.payDate ? ` · pay day ${dayLabel(dayKey(period.payDate), { weekday: false })}` : ""}`}
        back={{ href: "/dashboard/payroll", label: "Payroll" }}
        actions={<Chip tone={state.tone}>{state.label}</Chip>}
      />

      <p className="rounded-card bg-surface-container-lowest px-5 py-3 text-body-md text-on-surface-variant">
        {PAYROLL_STAGE_HINT[period.status]}
      </p>

      <Section title="The wage bill">
        <dl className="grid gap-4 text-body-md sm:grid-cols-3">
          <Detail label="Gross">{formatMoney(period.totalGross, currency)}</Detail>
          <Detail label="Deductions">{formatMoney(period.totalDeductions, currency)}</Detail>
          <Detail label="Net to pay">{formatMoney(period.totalNet, currency)}</Detail>
          <Detail label="Payslips">{period.payslipCount}</Detail>
          <Detail label="Generated by">{names.get(period.processedById) ?? "—"}</Detail>
          <Detail label="Approved by">{period.approvedAt ? (names.get(period.approvedById) ?? "someone") : "Not yet"}</Detail>
        </dl>
      </Section>

      {can(principal, "payroll.process", branchContext) ||
      can(principal, "payroll.approve", branchContext) ||
      can(principal, "payroll.mark_paid", branchContext) ? (
        <Section title="What happens next" description="Generating is a calculation, approving is the commitment, and marking paid records that money left.">
          <PayrollActions
            period={period}
            currency={currency}
            canProcess={can(principal, "payroll.process", branchContext)}
            canApprove={can(principal, "payroll.approve", branchContext)}
            canMarkPaid={can(principal, "payroll.mark_paid", branchContext)}
          />
        </Section>
      ) : null}

      {canSeePayslips ? (
        <Section title="Payslips" description="One per employee with attendance in the period.">
          {payslips.length ? (
            <ul className="flex flex-col gap-2">
              {payslips.map((payslip) => (
                <li key={payslip.id} className="flex flex-wrap items-center justify-between gap-3 rounded-field bg-surface-container-low px-4 py-3">
                  <div className="min-w-0">
                    <p className="text-label-bold text-on-surface">
                      <Link href={`/dashboard/payslips/${payslip.id}`} className="hover:underline">
                        {employeeName(payslip.employee)}
                      </Link>
                    </p>
                    <p className="mt-0.5 text-body-md text-on-surface-variant">
                      {Number(payslip.payableDays)} payable days · {durationLabel(payslip.workedMinutes)} worked
                      {payslip.overtimeMinutes ? ` · ${durationLabel(payslip.overtimeMinutes)} overtime` : ""}
                    </p>
                  </div>
                  <p className="text-right text-body-md text-on-surface-variant">
                    <span className="block text-label-bold text-on-surface">{formatMoney(payslip.netAmount, payslip.employee?.currency ?? currency)}</span>
                    gross {formatMoney(payslip.grossAmount, payslip.employee?.currency ?? currency)}
                  </p>
                </li>
              ))}
            </ul>
          ) : (
            <p className="text-body-md text-on-surface-variant">
              No payslips yet. Generating builds one per employee from their approved attendance — anything still
              waiting on a signature is not paid.
            </p>
          )}
        </Section>
      ) : null}

      {hasPermission(grantedPermissionKeys(principal), "journal_entries.read") && period.status !== "DRAFT" ? (
        <p className="text-body-md text-on-surface-variant">
          <Link href={`/dashboard/journal?source=PAYROLL`} className="text-primary hover:underline">
            See this run in the ledger
          </Link>
        </p>
      ) : null}
    </div>
  );
}

function Detail({ label, children }) {
  return (
    <div className="min-w-0">
      <dt className="text-label-bold font-normal text-on-surface-variant">{label}</dt>
      <dd className="mt-0.5 break-words text-on-surface">{children}</dd>
    </div>
  );
}
