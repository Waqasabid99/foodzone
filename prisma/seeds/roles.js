/**
 * Expands a role's patterns ("*", "orders.*", "orders.read") against the
 * catalogue, then removes anything listed in `excludes`.
 * Throws on a pattern that matches nothing, so a typo fails the seed loudly
 * instead of silently granting less than intended.
 */
export function resolvePermissionKeys(role, allKeys) {
  const granted = new Set();

  for (const pattern of role.permissions) {
    const matches =
      pattern === "*"
        ? allKeys
        : pattern.endsWith(".*")
          ? allKeys.filter((key) => key.startsWith(`${pattern.slice(0, -1)}`))
          : allKeys.filter((key) => key === pattern);

    if (matches.length === 0) {
      throw new Error(`Role "${role.key}": pattern "${pattern}" matched no permission`);
    }
    for (const key of matches) granted.add(key);
  }

  for (const pattern of role.excludes ?? []) {
    const matches =
      pattern.endsWith(".*")
        ? [...granted].filter((key) => key.startsWith(`${pattern.slice(0, -1)}`))
        : [...granted].filter((key) => key === pattern);

    if (matches.length === 0) {
      throw new Error(`Role "${role.key}": exclude "${pattern}" matched nothing it was granted`);
    }
    for (const key of matches) granted.delete(key);
  }

  return [...granted].sort();
}
