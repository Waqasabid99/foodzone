// System roles.
//
// These are seeded with isSystem = true: the admin UI may inspect them and
// assign them, but not rename or delete them. Admin-authored roles live
// alongside these and are never touched by the seed.
//
// `permissions` accepts exact keys ("orders.read"), whole modules
// ("orders.*") or "*" for everything, with `excludes` applied afterwards.
//
// `level` is seniority: lower is more senior, and a user may only grant roles
// at or below their own level. `scope` BRANCH means a grant should name a
// branch; GLOBAL means the role spans the company.

